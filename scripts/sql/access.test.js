// Replays scripts/sql on a real Postgres and tests what each Data API role can
// do to processed_bills. Needs a superuser connection:
//
//   TRACKER_TEST_POSTGRES_URL=postgresql://postgres@localhost/postgres bun run test
//
// Invariants, for each of the anon and authenticated roles:
// - it reads every processed_bills and pending_analysis row and column that
//   the table owner reads, whatever bills the writers store;
// - it holds SELECT on processed_bills and no other privilege on the table or
//   any of its columns, and none on the sequences the table owns, so it can't
//   insert, update, delete or truncate;
// - it holds SELECT and nothing else on every view built on processed_bills,
//   directly or through other views, so it can't write the table through one;
// - a stray insert, update or delete grant still changes no rows, and an
//   insert still fails. RLS doesn't cover TRUNCATE, so the revoke is its only
//   guard;
// - with an open policy, or an open policy and a PUBLIC grant of everything,
//   already on the table, the migration still closes writes and leaves the
//   privileges above.
// PUBLIC ends with no privilege on the table, its columns, its sequences or
// its views. The service role keeps every read and write the monitors and
// triage use. Each statement runs with the role claim PostgREST sets, so a
// policy that reads auth.role() sees what it would see on a real request.

