// What anon, authenticated and PUBLIC hold on processed_bills, its columns, the
// sequences it owns and each view built on it, directly or through other
// views, for every privilege type this server knows (17 adds MAINTAIN). It
// finds the sequences through pg_get_serial_sequence and the views through
// information_schema, not through the catalog walks 009 runs.
const REPORT = `
with recursive
  roles(role) as (values ('anon'::name), ('authenticated'::name), ('public'::name)),
  owner(oid) as (select oid from pg_roles where rolname = current_user),
  relation_privileges(privilege) as (
    select privilege_type from aclexplode(acldefault('r', (select oid from owner)))),
  sequence_privileges(privilege) as (
    select privilege_type from aclexplode(acldefault('s', (select oid from owner)))),
  column_privileges(privilege) as (
    values ('SELECT'), ('INSERT'), ('UPDATE'), ('REFERENCES')),
  sequences(oid) as (
    select pg_get_serial_sequence('processed_bills', attname)::regclass
    from pg_attribute
    where attrelid = 'processed_bills'::regclass and attnum > 0 and not attisdropped
      and pg_get_serial_sequence('processed_bills', attname) is not null),
  views(oid) as (
    select format('%I.%I', view_schema, view_name)::regclass
    from information_schema.view_table_usage
    where table_schema = 'public' and table_name = 'processed_bills'
    union
    select format('%I.%I', u.view_schema, u.view_name)::regclass
    from information_schema.view_table_usage as u
    join views as v on format('%I.%I', u.table_schema, u.table_name)::regclass = v.oid),
  checks(kind, object, role, privilege, held) as (
    select 'table', 'processed_bills', role, privilege,
      has_table_privilege(role, 'processed_bills', privilege)
    from roles, relation_privileges
    union all
    select 'table columns', 'processed_bills', role, privilege,
      has_any_column_privilege(role, 'processed_bills', privilege)
    from roles, column_privileges
    union all
    select 'column grant', 'processed_bills.' || a.attname,
      case x.grantee when 0 then 'public' else x.grantee::regrole::text end,
      x.privilege_type, true
    from pg_attribute as a, aclexplode(a.attacl) as x
    where a.attrelid = 'processed_bills'::regclass
      and (x.grantee = 0 or x.grantee::regrole::text in ('anon', 'authenticated'))
    union all
    select 'sequence', s.oid::regclass::text, role, privilege,
      has_sequence_privilege(role, s.oid, privilege)
    from sequences as s, roles, sequence_privileges
    union all
    select 'view', v.oid::regclass::text, role, privilege,
      has_table_privilege(role, v.oid, privilege)
    from views as v, roles, relation_privileges
    union all
    select 'view columns', v.oid::regclass::text, role, privilege,
      has_any_column_privilege(role, v.oid, privilege)
    from views as v, roles, column_privileges)
select jsonb_agg(to_jsonb(checks) order by kind, object, role, privilege) from checks`;
const TABLE_PRIVILEGES = ["DELETE", "INSERT", "REFERENCES", "SELECT", "TRIGGER", "TRUNCATE", "UPDATE"];
// anon and authenticated keep SELECT on the table, its columns and its views,
// and nothing else. PUBLIC keeps nothing, and no column grant names any of them.
const allowed = ({ kind, role, privilege }) =>
  role !== "public" && privilege === "SELECT" && kind !== "sequence" && kind !== "column grant";
const violations = (checks) => checks.filter((check) => check.held !== allowed(check));

// Bills as the writers store them, with ids from LegiScan's own range,
// openstates_monitor.py's 10,000,000 to 99,999,999 and congress_monitor.py's
// 20,000,000 to 29,999,999.
