    title: fc.constantFrom("Earned income tax credit", "Children's tax rebate", null),
    status: fc.constantFrom("Prefiled", "Introduced", "Passed", "Enacted", null),
    lastActionDate: fc.constantFrom("2025-12-31", "2026-01-01", "2026-03-10", null),
    confidenceScore: fc.option(fc.integer({ min: 0, max: 100 })),
    skippedReason: fc.constantFrom("not_modelable", "Not relevant", null),
    matchedQuery: fc.constantFrom("congress-discovery", "curated-federal-seed", "earned income tax credit", null),
    source: fc.constantFrom("legiscan", "openstates", null),
    reformType: fc.constantFrom("parametric", "structural", "unknown", null),
